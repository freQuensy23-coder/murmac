import AppKit
import ApplicationServices
import CoreGraphics
import Foundation
import MurmacCore

/// Wispr Flow-style text insertion on macOS:
/// 1. Snapshot existing `NSPasteboard.general` items + `changeCount` (preserving original clipboard across back-to-back pastes).
/// 2. Write transcript tagged with `org.nspasteboard.TransientType` so clipboard managers ignore the swap.
/// 3. Synthesize `Cmd+V` via `CGEvent` using `.privateState` (prevents physical Right Option bleed into `Cmd+Opt+V`).
/// 4. After 450 ms, if `changeCount` hasn't changed, restore the user's previous clipboard.
/// 5. If no field is focused or Accessibility is denied, keep text on clipboard as normal copy (`copiedOnly`).
public final class MacTextInserter: TextInserterPort, @unchecked Sendable {
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private static let maxSnapshotBytes = 25 * 1024 * 1024

    private static let terminalFragments = ["terminal", "iterm", "ghostty", "warp", "kitty", "alacritty", "wezterm"]

    @MainActor private var pendingRestoreTask: Task<Void, Never>?
    @MainActor private var originalClipboardSnapshot: [[NSPasteboard.PasteboardType: Data]]?

    public init() {}

    public func copyToClipboard(_ text: String) {
        let work: @Sendable () -> Void = {
            let pb = NSPasteboard.general
            pb.clearContents()
            pb.setString(text, forType: .string)
        }
        if Thread.isMainThread { work() } else { DispatchQueue.main.async(execute: work) }
    }

    public func insert(text: String, target: A11ySnapshot?, restoreClipboard: Bool) async -> InsertOutcome {
        guard AXIsProcessTrusted() else {
            copyToClipboard(text)
            return .copiedOnly
        }
        let lowerBundle = (target?.bundleId ?? "").lowercased()
        let isTerminal = Self.terminalFragments.contains { lowerBundle.contains($0) }
        if let target, let f = target.field, !f.isEditable && !isTerminal {
            copyToClipboard(text)
            return .copiedOnly
        }
        // If Finder desktop has no focused editable element, copy instead of blind Cmd+V
        if lowerBundle == "com.apple.finder" && target?.field?.isEditable != true {
            copyToClipboard(text)
            return .copiedOnly
        }

        let expectedChangeCount: Int = await MainActor.run {
            let pb = NSPasteboard.general
            if restoreClipboard {
                // If an earlier restore is still pending (back-to-back dictations), keep the TRUE original snapshot!
                if pendingRestoreTask == nil {
                    originalClipboardSnapshot = Self.snapshotPasteboard(pb)
                }
                pendingRestoreTask?.cancel()
                pendingRestoreTask = nil
            }
            pb.clearContents()
            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            if restoreClipboard {
                item.setData(Data(), forType: Self.transientType)
                item.setData(Data(), forType: Self.autoGeneratedType)
            }
            pb.writeObjects([item])
            return pb.changeCount
        }

        let posted = postCmdV()
        guard posted else {
            await MainActor.run {
                pendingRestoreTask?.cancel()
                pendingRestoreTask = nil
                originalClipboardSnapshot = nil
            }
            copyToClipboard(text)
            return .copiedOnly
        }

        if restoreClipboard {
            await MainActor.run {
                pendingRestoreTask = Task { @MainActor [weak self] in
                    try? await Task.sleep(nanoseconds: 450_000_000)
                    guard let self, !Task.isCancelled else { return }
                    let pb = NSPasteboard.general
                    let saved = self.originalClipboardSnapshot ?? []
                    self.originalClipboardSnapshot = nil
                    self.pendingRestoreTask = nil
                    guard pb.changeCount == expectedChangeCount else { return }
                    Self.restorePasteboard(pb, items: saved)
                }
            }
        }

        return .inserted(.paste)
    }

    private func postCmdV() -> Bool {
        // Use .privateState so lingering physical modifiers (e.g., Right Option release) never bleed into Cmd+V
        guard let src = CGEventSource(stateID: .privateState) else { return false }
        let vKeyCode: CGKeyCode = 0x09 // 'v'
        guard let down = CGEvent(keyboardEventSource: src, virtualKey: vKeyCode, keyDown: true),
              let up = CGEvent(keyboardEventSource: src, virtualKey: vKeyCode, keyDown: false) else {
            return false
        }
        down.flags = .maskCommand
        up.flags = .maskCommand
        down.post(tap: .cghidEventTap)
        up.post(tap: .cghidEventTap)
        return true
    }

    @MainActor
    private static func snapshotPasteboard(_ pb: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]] {
        guard let items = pb.pasteboardItems else { return [] }
        var totalBytes = 0
        return items.compactMap { item in
            var dict: [NSPasteboard.PasteboardType: Data] = [:]
            for t in item.types {
                // Skip promised file types and transient metadata to avoid blocking IPC materialization
                if t == transientType || t == autoGeneratedType || t.rawValue.contains("promise") { continue }
                if let d = item.data(forType: t) {
                    if totalBytes + d.count > maxSnapshotBytes { continue }
                    totalBytes += d.count
                    dict[t] = d
                }
            }
            return dict.isEmpty ? nil : dict
        }
    }

    @MainActor
    private static func restorePasteboard(_ pb: NSPasteboard, items: [[NSPasteboard.PasteboardType: Data]]) {
        pb.clearContents()
        guard !items.isEmpty else { return }
        let restored: [NSPasteboardItem] = items.map { dict in
            let item = NSPasteboardItem()
            for (t, d) in dict {
                item.setData(d, forType: t)
            }
            return item
        }
        pb.writeObjects(restored)
    }
}
